'use strict';
// Generates apps-script/Domain.gs from docs/src/domain/*.js so the backend and the PWA
// run the same financial engine. Apps Script has no module system: the domain files are
// concatenated in files.json order and attach to globalThis.FFDomain.
// Usage: node tools/build-apps-script.cjs [--check]
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'docs', 'src', 'domain');
const files = JSON.parse(fs.readFileSync(path.join(dir, 'files.json'), 'utf8'));
const out = path.join(root, 'apps-script', 'Domain.gs');
const body = '// GENERATED by tools/build-apps-script.cjs from docs/src/domain — do not edit by hand.\n' +
  '// Run `npm run build:apps-script` after changing the domain modules.\n' +
  files.map(f => `\n// ---- ${f} ----\n` + fs.readFileSync(path.join(dir, f), 'utf8')).join('');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== body) { console.error('apps-script/Domain.gs is stale. Run: npm run build:apps-script'); process.exit(1); }
  console.log('apps-script/Domain.gs is up to date');
} else { fs.writeFileSync(out, body); console.log('wrote ' + path.relative(root, out)); }
