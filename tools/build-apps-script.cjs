'use strict';
// Builds the Apps Script backend artifacts:
//  1. apps-script/Domain.gs — docs/src/domain/*.js concatenated (files.json order), so the backend
//     and the PWA run the same financial engine.
//  2. apps-script/dist/Code.gs — ONE file containing every backend file in apps-script/files.json
//     order. Paste it as the only Code.gs in the Apps Script editor (no multi-file setup needed).
// Usage: node tools/build-apps-script.cjs [--check]
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'docs', 'src', 'domain');
const files = JSON.parse(fs.readFileSync(path.join(dir, 'files.json'), 'utf8'));
const domainOut = path.join(root, 'apps-script', 'Domain.gs');
const domainBody = '// GENERATED by tools/build-apps-script.cjs from docs/src/domain — do not edit by hand.\n' +
  '// Run `npm run build:apps-script` after changing the domain modules.\n' +
  files.map(f => `\n// ---- ${f} ----\n` + fs.readFileSync(path.join(dir, f), 'utf8')).join('');

function bundleBody(domain) {
  const backend = JSON.parse(fs.readFileSync(path.join(root, 'apps-script', 'files.json'), 'utf8'));
  const header = [
    '// Family Finance — Google Apps Script backend, SINGLE-FILE BUNDLE (apiVersion 3).',
    '// GENERATED by tools/build-apps-script.cjs from apps-script/*.gs — do not edit by hand.',
    '//',
    '// Install: Apps Script editor → replace the entire contents of Code.gs with this file → Save →',
    '// Deploy → Manage deployments → Edit (pencil) → Version: New version → Deploy.',
    '// Editing the EXISTING deployment keeps the same /exec URL, so APK 2.3.0 and the web app keep syncing.',
    '// Keep the Script Properties FAMILY_ACCESS_TOKEN and DEEPSEEK_API_KEY. Never paste them here.',
    '// Optional 3.0 features (assets, recurring): run migrationsDryRun, then migrationsApply, from the editor.',
    ''
  ].join('\n');
  return header + backend.map(f => `\n// ==== ${f} ====\n` + (f === 'Domain.gs' ? domain : fs.readFileSync(path.join(root, 'apps-script', f), 'utf8'))).join('');
}
const bundleOut = path.join(root, 'apps-script', 'dist', 'Code.gs');

if (process.argv.includes('--check')) {
  const stale = [];
  if ((fs.existsSync(domainOut) ? fs.readFileSync(domainOut, 'utf8') : '') !== domainBody) stale.push('apps-script/Domain.gs');
  if ((fs.existsSync(bundleOut) ? fs.readFileSync(bundleOut, 'utf8') : '') !== bundleBody(domainBody)) stale.push('apps-script/dist/Code.gs');
  if (stale.length) { console.error(stale.join(', ') + ' stale. Run: npm run build:apps-script'); process.exit(1); }
  console.log('apps-script/Domain.gs and apps-script/dist/Code.gs are up to date');
} else {
  fs.writeFileSync(domainOut, domainBody);
  fs.mkdirSync(path.dirname(bundleOut), { recursive: true });
  fs.writeFileSync(bundleOut, bundleBody(domainBody));
  console.log('wrote apps-script/Domain.gs and apps-script/dist/Code.gs');
}
